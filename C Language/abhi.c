#include <stdio.h>

int main() {
    int marks;

    printf("अपने अंक दर्ज करें: ");
    scanf("%d", &marks);  // अंक इनपुट लेना

    if (marks >= 50) {
        // अगर अंक 50 या उससे अधिक हैं तो "पास" दिखाओ
        printf("बधाई हो! आपने परीक्षा पास की।\n");
    } else {
        // अगर अंक 50 से कम हैं तो "फेल" दिखाओ
        printf("मुझे खेद है, आप परीक्षा में फेल हो गए।\n");
    }

    return 0;
}
